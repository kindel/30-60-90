#!/usr/bin/env node
"use strict";

var fs = require("fs");
var path = require("path");

var root = path.join(__dirname, "..");
var templatesDir = path.join(root, "templates");
var outPath = path.join(root, "js", "templates.js");

function readJson(file) {
  return JSON.parse(fs.readFileSync(file, "utf8"));
}

function buildBundle() {
  var manifest = readJson(path.join(templatesDir, "index.json"));
  var templates = {};
  (manifest.templates || []).forEach(function (entry) {
    if (!entry || !entry.id || !entry.file) return;
    templates[entry.id] = readJson(path.join(templatesDir, entry.file));
  });
  var facetSets = null;
  var facetSetsPath = path.join(templatesDir, "facet-sets.json");
  if (fs.existsSync(facetSetsPath)) {
    facetSets = readJson(facetSetsPath);
  }
  return {
    kind: "kindel.30-60-90.templates-bundle",
    version: 1,
    manifest: manifest,
    templates: templates,
    facetSets: facetSets
  };
}

function bundleSource(bundle) {
  return [
    "/* generated by scripts/build-templates.js; do not edit */",
    "var KINDEL_TEMPLATES = " + JSON.stringify(bundle, null, 2) + ";",
    "if (typeof globalThis !== \"undefined\") globalThis.KINDEL_TEMPLATES = KINDEL_TEMPLATES;",
    "if (typeof window !== \"undefined\") window.KINDEL_TEMPLATES = KINDEL_TEMPLATES;",
    ""
  ].join("\n");
}

function writeBundle() {
  var src = bundleSource(buildBundle());
  fs.writeFileSync(outPath, src);
  return outPath;
}

function isBundleStale() {
  if (!fs.existsSync(outPath)) return true;
  var expected = bundleSource(buildBundle());
  var actual = fs.readFileSync(outPath, "utf8");
  return expected !== actual;
}

if (require.main === module) {
  var dest = writeBundle();
  console.log("Wrote " + path.relative(root, dest));
}

module.exports = {
  buildBundle: buildBundle,
  bundleSource: bundleSource,
  writeBundle: writeBundle,
  isBundleStale: isBundleStale,
  outPath: outPath
};
